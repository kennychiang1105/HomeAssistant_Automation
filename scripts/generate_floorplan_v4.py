def overlay_style(mode):
    if mode == "color":
        return (
            "{% set on = is_state(config.entity, 'on') %}\n"
            "{% set b = state_attr(config.entity, 'brightness') | default(255, true) %}\n"
            "{% set hs = state_attr(config.entity, 'hs_color') | default([0, 0], true) %}\n"
            ":host {\n"
            "  opacity: {{ (b / 255) if on else 0 }} !important;\n"
            "  filter: hue-rotate({{ hs[0] }}deg) saturate({{ hs[1] / 100 }});\n"
            "  mix-blend-mode: lighten;\n"
            "  pointer-events: none;\n"
            "  transition: opacity .4s;\n"
            "}\n"
        )
    return (
        ":host {\n"
        "  opacity: {{ 1 if is_state(config.entity, 'on') else 0 }} !important;\n"
        "  mix-blend-mode: lighten;\n"
        "  pointer-events: none;\n"
        "  transition: opacity .4s;\n"
        "}\n"
    )


def build_floor(key, fl, coords, manifest_lights):
    f = key.lower()
    real_dir = ROOT / "www/floorplan/v4" / f
    base_real = next((p for p in (real_dir / "base.webp", real_dir / "base.png") if p.exists()), None)
    base = f"/local/floorplan/v4/{f}/{base_real.name}" if base_real else f"/local/floorplan/3d/floor_{f}_3d.svg?v=2"
    pos = coords.get(key, {}).get("entities", {})
    elements = []
    # overlays first, so hotspots stay on top
    for lt in manifest_lights:
        img = real_dir / Path(lt["image"]).name
        if not img.exists():
            continue
        elements.append({
            "type": "image", "entity": lt["entity"],
            "image": f"/local/floorplan/v4/{f}/{img.name}",
            "tap_action": {"action": "none"},
            "style": {"top": "50%", "left": "50%", "width": "100%"},
            "card_mod": {"style": overlay_style(lt["mode"])},
        })
    for e in fl["entities"]:
        eid, dom = e["entity_id"], e["domain"]
        lt = next((x for x in manifest_lights if x["entity"] == eid), None)
        p = None
        if lt and lt.get("pos_pct"):
            p = {"pct_left": lt["pos_pct"][0], "pct_top": lt["pos_pct"][1]}
        p = p or pos.get(eid)
        if not p:
            continue
        style = {"left": f"{p['pct_left']}%", "top": f"{p['pct_top']}%"}
        if dom == "sensor" and ("temperature" in eid or "wen_du" in eid):
            elements.append({
                "type": "state-label", "entity": eid, "suffix": "°C",
                "style": {**style, "color": "#ff5252", "font-size": "13px", "font-weight": "700",
                          "text-shadow": "0 0 3px #000, 0 0 6px #000"},
            })
        elif dom in TOGGLE or dom in ("lock", "climate", "camera") or (
            dom == "binary_sensor" and re.search(r"motion|person", eid)
        ):
            plug = dom == "switch" and not is_light(e)
            el = {
                "type": "state-icon", "entity": eid, "state_color": True,
                "icon": "mdi:power-socket-eu" if plug else ICONS.get(dom),
                "style": {**style, "--mdc-icon-size": "20px", "color": "#fff",
                          "width": "30px", "height": "30px", "display": "flex",
                          "align-items": "center", "justify-content": "center",
                          "box-sizing": "border-box", "background": "rgba(30,30,30,.72)",
                          "border": "1px solid rgba(255,255,255,.55)", "border-radius": "50%"},
                "tap_action": {"action": "toggle"} if dom in TOGGLE else {"action": "more-info"},
                "hold_action": {"action": "more-info"},
            }
            elements.append(el)
    return {"type": "picture-elements", "image": base, "elements": elements}


def build_controls(key, fl):
    """Per-floor room-control grid (button-card iOS templates), shown under the map."""
    seen, cards = set(), []
    for e in fl["entities"]:
        eid, dom = e["entity_id"], e["domain"]
        if eid in seen or dom not in ("light", "switch", "cover", "lock", "fan", "climate"):
            continue
        seen.add(eid)
        tpl = {"light": "ios_light_card", "cover": "ios_cover_card", "lock": "ios_lock_card"}.get(
            dom, "ios_light_card" if is_light(e) else "ios_device_card")
        card = {"type": "custom:button-card", "template": tpl, "entity": eid}
        if dom in ("fan", "climate"):
            card["tap_action"] = {"action": "more-info"}
        cards.append(card)
    return {"type": "grid", "columns": 2, "square": False, "cards": cards}


def build():
    graph = json.loads(GRAPH.read_text())
    coords = json.loads(COORDS.read_text())
    manifest_data = yaml.safe_load(MANIFEST.read_text())["floors"]
    OUT_DIR.mkdir(exist_ok=True)
    for old in OUT_DIR.glob("*.yaml"):
        old.unlink()
    maps, ctrls = {}, {}
    for key, fl in graph["floors"].items():
        m = build_floor(key, fl, coords, manifest_data[key.lower()]["lights"])
        maps[key] = {"label": key, "card": m}
        ctrls[key] = {"label": key, "card": build_controls(key, fl)}
        print(f"{key}: {len(m['elements'])} map elements, base={m['image']}")
    maps["全棟"] = {"label": "全棟", "card": {"type": "picture", "image": "/local/floorplan/3d/floor_all_3d.svg?v=2",
                                              "tap_action": {"action": "none"}}}
    ctrls["全棟"] = {"label": "全棟", "card": {"type": "markdown", "content": "切換到各樓層即可操作該層設備。"}}
    header = "# generated by scripts/generate_floorplan_v4.py - do not edit by hand\n"
    for name, typ, floors in (("map_card", "custom:floorplan-v4-card", maps),
                              ("controls_card", "custom:floorplan-v4-controls", ctrls)):
        body = {"type": typ, "default": "2F", "floors": floors}
        (OUT_DIR / f"{name}.yaml").write_text(
            header + yaml.safe_dump(body, allow_unicode=True, sort_keys=False, width=120))
        print(f"wrote floorplan_v4/{name}.yaml")


def plans():
    """Copy the 2D plan SVGs (without the HA entity layer) to www/floorplan/v4/plans/."""
    import xml.etree.ElementTree as ET

    ET.register_namespace("", "http://www.w3.org/2000/svg")
    graph = json.loads(GRAPH.read_text())
    out = ROOT / "www/floorplan/v4/plans"
    out.mkdir(parents=True, exist_ok=True)
    for key, fl in graph["floors"].items():
        tree = ET.parse(ROOT / "floorplan_src" / fl["svg_file"])
        for parent in list(tree.getroot().iter()):
            for child in list(parent):
                if child.get("id", "").startswith("HA"):
                    parent.remove(child)
        # Safari gives no CSSOM for DOMParser documents, so three.js SVGLoader cannot resolve
        # class="stN" fills there. Inline fill/stroke from the <style> block onto each element.
        ns = "{http://www.w3.org/2000/svg}"
        css = "".join(e.text or "" for e in tree.getroot().iter(ns + "style"))
        rules = {}
        for m in re.finditer(r"([^{}]+)\{([^}]*)\}", css):
            props = dict((k.strip(), v.strip()) for k, v in
                         (d.split(":", 1) for d in m.group(2).split(";") if ":" in d))
            for sel in m.group(1).split(","):
                rules.setdefault(sel.strip().lstrip("."), {}).update(props)
        for el in tree.getroot().iter():
            for cls in (el.get("class") or "").split():
                for prop in ("fill", "stroke", "stroke-width", "fill-rule"):
                    if prop in rules.get(cls, {}) and el.get(prop) is None:
                        el.set(prop, rules[cls][prop])
        dest = out / f"floor_{key.lower()}.svg"
        tree.write(dest, encoding="utf-8", xml_declaration=True)
        print(f"wrote {dest.relative_to(ROOT)}")


DEVICE_DOMAINS = {"light", "switch", "fan", "cover", "lock", "climate", "camera", "media_player"}


def kind_of(e):
    eid, dom = e["entity_id"], e["domain"]
    name = eid.split(".", 1)[1]
    if dom == "sensor":
        if "temperature" in name or "wen_du" in name:
            return "temp"
        if "humidity" in name or "shi_du" in name:
            return "hum"
        if re.search(r"co2|pm2_5|_co$", name):
            return "value"
        if "tesla_wall_connector_status" in name:
            return "charger"
        if re.match(r"(u6_|udm)", name) and name.endswith("_state"):   # UniFi gateway / access points
            return "ap"
        return None
    if dom == "binary_sensor":
        if "person" in name:
            return "person"
        if "motion" in name:
            return "motion"
        if "wei_xian" in name:
            return "safety"
        return None
    if dom == "switch":
        return "switch" if is_light(e) else "plug"
    return dom if dom in DEVICE_DOMAINS else None


def devices(fl):
    out, seen = [], set()
    for e in fl["entities"]:
        eid = e["entity_id"]
        kind = kind_of(e)
        if eid in seen or not kind:
            continue
        seen.add(eid)
        room = re.sub(r"^\dF\s*", "", e.get("room", ""))[:2]
        out.append({"entity": eid, "kind": kind, "x": round(e["coordinates"]["x"], 1),
                    "y": round(e["coordinates"]["y"], 1), "light": is_light(e), "room": room})
    return out


def geometry(svg_name, top_floor=False):
    """Detect stairs, windows and doors in a plan SVG (heuristics on the Illustrator export)."""
    import xml.etree.ElementTree as ET

    ns = "{http://www.w3.org/2000/svg}"
    root = ET.parse(ROOT / "floorplan_src" / svg_name).getroot()
    css = "".join(e.text or "" for e in root.iter(ns + "style"))
    fills = {}
    for m in re.finditer(r"([^{}]+)\{([^}]*)\}", css):
        fm = re.search(r"fill:\s*([^;]+)", m.group(2))
        if fm:
            for sel in m.group(1).split(","):
                fills[sel.strip().lstrip(".")] = fm.group(1).strip().lower()
    stairs, seen = [], set()
    for g in root.iter(ns + "g"):
        if g.get("id", "").startswith("HA"):
            continue
        rects = [c for c in g if c.tag == ns + "rect" and not c.get("transform")]
        paths = [c.get("d", "") for c in g if c.tag == ns + "path"]
        for d in paths:
            vs, hs = re.findall(r"[vV]-?[\d.]+", d), re.findall(r"[hH]-?[\d.]+", d)
            n = max(len(vs), len(hs))
            if not 6 <= n <= 14:
                continue
            for r in rects:
                x, y, w, h = (float(r.get(k, 0)) for k in ("x", "y", "width", "height"))
                if not (55 <= min(w, h) <= 130 and max(w, h) >= 80) or (x, y, w, h) in seen:
                    continue
                seen.add((x, y, w, h))
                # arrow head "M x0,y0 l dx1,dy1 dx2,dy2": its tip shows the walking (up) direction
                tip = None
                for a in paths:
                    m = re.search(r"M([\d.]+),([\d.]+)l(-?[\d.]+)[, ]?(-?[\d.]+)", a)
                    if m:
                        tip = (float(m.group(1)) + float(m.group(3)), float(m.group(2)) + float(m.group(4)))
                run_axis = "x" if w >= h else "y"
                centre = x + w / 2 if run_axis == "x" else y + h / 2
                dirn = 1 if tip is None or (tip[0] if run_axis == "x" else tip[1]) >= centre else -1
                stairs.append({"x": x, "y": y, "w": w, "h": h, "axis": run_axis, "steps": n + 1,
                               "dir": dirn, "h0": 0, "h1": 34})
    # U-shaped staircase: two parallel flights side by side -> first flight 0..17, landing, second 17..34.
    # The southern flight is walked first, which chains the arrows from floor to floor (3F -> 4F -> 5F).
    for a in stairs:
        for b in stairs:
            if a is b or a["axis"] != b["axis"]:
                continue
            if a["axis"] == "x":
                same = abs(a["x"] - b["x"]) < 6 and abs(a["w"] - b["w"]) < 6
                near = -12 <= b["y"] - (a["y"] + a["h"]) < 30
            else:
                same = abs(a["y"] - b["y"]) < 6 and abs(a["h"] - b["h"]) < 6
                near = -12 <= b["x"] - (a["x"] + a["w"]) < 30
            if same and near and a["dir"] != b["dir"]:
                b["h0"], b["h1"], b["landing"] = 0, 17, True
                a["h0"], a["h1"] = 17, 34
    if top_floor:
        for st in stairs:                         # top floor: the staircase goes down through a slab opening
            if st["h0"] == 0 and st["h1"] == 34:
                st["h0"], st["h1"], st["dir"] = 0, -34, -st["dir"]
    openings, centers = [], set()
    for r in root.iter(ns + "rect"):
        if r.get("transform") or fills.get(r.get("class", ""), "#000") != "#fff":
            continue
        x, y, w, h = (float(r.get(k, 0)) for k in ("x", "y", "width", "height"))
        thin, long_ = min(w, h), max(w, h)
        if long_ < 25:
            continue
        kind = "window" if thin <= 1.5 else "door" if 4.5 <= thin <= 5.5 else None
        key = (round(x + w / 2), round(y + h / 2))
        if kind and key not in centers and not any(
                s["x"] <= x <= s["x"] + s["w"] and s["y"] <= y <= s["y"] + s["h"] for s in stairs):
            centers.add(key)
            openings.append({"kind": kind, "x": round(x, 1), "y": round(y, 1), "w": round(w, 1), "h": round(h, 1)})
    return stairs, openings


