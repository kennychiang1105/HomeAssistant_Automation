HEIGHT_HINT = {"light": 30, "switch": 24, "plug": 4, "fan": 15, "climate": 30, "camera": 34, "motion": 28, "person": 34,
               "temp": 15, "hum": 15, "value": 15, "safety": 15, "cover": 17, "lock": 12, "media_player": 12, "charger": 18}


def positions():
    """Write the entity position table (YAML / JSON / Markdown) for automations, and sync the scene graph + SVG."""
    graph, floors = scene_floors()
    rows = []
    for key, fl in floors.items():
        lights = [d for d in fl["devices"] if d["kind"] in ("light", "switch") and d["light"] or d["kind"] == "light"]
        clusters = []
        for d in lights:
            c = next((k for k in clusters if k["room"] == d["zone"] and any(
                math.hypot(o["x"] - d["x"], o["y"] - d["y"]) < 110 for o in k["items"])), None)
            if c:
                c["items"].append(d)
            else:
                clusters.append({"room": d["zone"], "items": [d]})
        group_of = {}
        for i, c in enumerate(clusters):
            if len(c["items"]) >= 2:
                for d in c["items"]:
                    group_of[d["entity"]] = f"{key.lower()}_{c['room']}_lights_{i + 1}"
        for d in fl["devices"]:
            zone = d["zone"]
            rows.append({
                "entity_id": d["entity"], "name": d.get("name") or d["entity"], "in_ha": bool(d.get("name")),
                "floor": key, "zone": zone,
                "kind": d["kind"], "x": d["x"], "y": d["y"],
                "world": {"x": round(d["x"] - fl["width"] / 2, 1), "z": round(d["y"] - fl["height"] / 2, 1),
                          "y": HEIGHT_HINT.get(d["kind"], 10)},
                "light_group": group_of.get(d["entity"]),
                "yaw_deg": d.get("yaw"), "source": d["src"],
            })
    meta = {"generated": "2026-10-04", "coordinate_system": "plan px, origin top-left of each floor SVG, +x east, +y south; "
            "world = plan - floor_size/2 (three.js x,z), y = height hint above floor",
            "floor_size": {k: [f["width"], f["height"]] for k, f in floors.items()}}
    (ROOT / "entity_positions.json").write_text(json.dumps({"meta": meta, "entities": rows}, ensure_ascii=False, indent=1))
    (ROOT / "entity_positions.yaml").write_text(
        "# generated by scripts/generate_floorplan_v4.py positions - do not edit by hand\n"
        + yaml.safe_dump({"meta": meta, "entities": rows}, allow_unicode=True, sort_keys=False, width=140))
    md = ["# 實體位置對照表 (ENTITY_POSITIONS)", "",
          "> 由 `scripts/generate_floorplan_v4.py positions` 自動產生。來源：平面圖 SVG 實體圖層 + 使用者在 3D 卡片「✎ 調整位置」存下的修正（`來源=調整`）。",
          "> 座標：每層平面圖像素，原點在左上角，x 向東、y 向南。3D 世界座標 = 平面座標 − 樓層尺寸/2。", "",
          "樓層尺寸：" + "、".join(f"{k} {int(v[0])}×{int(v[1])}" for k, v in meta["floor_size"].items()), ""]
    for key in floors:
        md += [f"## {key}", "", "| 區域 | 名稱 | 實體 | 類型 | x | y | 燈群組 | 來源 |", "|---|---|---|---|---|---|---|---|"]
        for r in sorted((r for r in rows if r["floor"] == key), key=lambda r: (r["zone"], r["kind"], r["x"])):
            md.append(f"| {r['zone']} | {r['name']} | `{r['entity_id']}` | {r['kind']} | {r['x']} | {r['y']} | "
                      f"{r['light_group'] or ''} | {'調整' if r['source'] == 'adjusted' else '原圖'}{'' if r['in_ha'] else ' ⚠HA無此實體'} |")
        md.append("")
    (ROOT / "ENTITY_POSITIONS.md").write_text("\n".join(md) + "\n")
    # keep the scene graph and SVG entity layer in sync with the adjusted positions
    n_graph = n_svg = 0
    for key, fl in graph["floors"].items():
        for e in fl["entities"]:
            ov = OVERRIDES.get(f"{key}|{e['entity_id']}")
            if ov:
                e["coordinates"] = {"x": ov[0], "y": ov[1]}; n_graph += 1
    GRAPH.write_text(json.dumps(graph, ensure_ascii=False, indent=2))
    for key, fl in graph["floors"].items():
        path = ROOT / "floorplan_src" / fl["svg_file"]
        txt = path.read_text()
        for k, ov in OVERRIDES.items():
            f, eid = k.split("|")
            if f != key:
                continue
            esc = eid.replace("_", "_x5F_")
            pat = re.compile(r'(<circle id="' + re.escape(esc) + r'"[^>]*?)cx="[^"]*" cy="[^"]*"')
            txt, n = pat.subn(lambda m: f'{m.group(1)}cx="{ov[0]}" cy="{ov[1]}"', txt)
            n_svg += n
        path.write_text(txt)
    print(f"wrote entity_positions.yaml/.json, ENTITY_POSITIONS.md ({len(rows)} entities); "
          f"synced {n_graph} scene-graph entries and {n_svg} SVG circles")


