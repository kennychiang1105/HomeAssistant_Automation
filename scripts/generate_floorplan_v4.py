# switch.* entities that are lamps (name ends in "deng") but not plugs/sockets
LAMP_SWITCH = re.compile(r"deng(_\d+)?$")


def is_light(e):
    eid = e["entity_id"]
    if e["domain"] == "light":
        return True
    return e["domain"] == "switch" and bool(LAMP_SWITCH.search(eid.split(".", 1)[1]))


def manifest():
    graph = json.loads(GRAPH.read_text())
    out = [
        "# V4.0-beta 1 render manifest (generated by scripts/generate_floorplan_v4.py)",
        "# Per floor: render one base image (all lights off) and one image per light",
        "# (only that light on). Same camera, same size, same framing for every image.",
        "# Recommended size: 1600x1000 WebP/PNG. Put files in www/floorplan/v4/<floor>/.",
        "floors:",
    ]
    for key, fl in graph["floors"].items():
        f = key.lower()
        out += [
            f"  {f}:",
            f"    name: \"{fl['name']}\"",
            f"    base: www/floorplan/v4/{f}/base.webp",
            "    lights:",
        ]
        for e in fl["entities"]:
            if not is_light(e):
                continue
            eid = e["entity_id"]
            kind = "color" if e["domain"] == "light" else "onoff"
            name = eid.split(".", 1)[1]
            out += [
                f"      - entity: {eid}",
                f"        room: \"{e['room']}\"",
                f"        mode: {kind}   # color = hue/brightness sync, onoff = on/off overlay",
                f"        image: www/floorplan/v4/{f}/{name}.webp",
                f"        pos_2d: [{e['coordinates']['x']}, {e['coordinates']['y']}]",
            ]
    MANIFEST.write_text("\n".join(out) + "\n")
    n = sum(1 for fl in graph["floors"].values() for e in fl["entities"] if is_light(e))
    print(f"wrote {MANIFEST} ({n} light overlays + {len(graph['floors'])} base images)")


